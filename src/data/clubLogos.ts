// ⚡ O(1) Anında Erişim İçin Ön Bellek (Cache)
const BADGE_CACHE = new Map<string, ClubBadgeInfo>();

/**
 * Kulüp adına göre rozet / logo bilgilerini getirir.
 * 1. Doğrudan eşleşme
 * 2. Eş anlamlı (alias) eşleşmesi
 * 3. Büyük/küçük harf duyarsız kısmi arama
 * 4. Bulunamazsa şık gradient + harf rozeti üretir
 */
export function getClubBadge(clubName: string): ClubBadgeInfo {
  if (!clubName) {
    return {
      name: "Bilinmeyen",
      short: "BIL",
      primaryColor: "#1E3A8A",
      secondaryColor: "#3B82F6",
      textColor: "#FFFFFF",
      badgeShape: "shield",
    };
  }

  // 1. Önbellekte varsa anında dön (O(1))
  if (BADGE_CACHE.has(clubName)) {
    return BADGE_CACHE.get(clubName)!;
  }

  let result: ClubBadgeInfo;

  // 2. Tam doğrudan eşleşme
  if (CLUB_DATABASE[clubName]) {
    result = CLUB_DATABASE[clubName];
  } else {
    // 3. Alias sözlüğü kontrolü
    const aliasTarget = CLUB_ALIASES[clubName];
    if (aliasTarget && CLUB_DATABASE[aliasTarget]) {
      result = CLUB_DATABASE[aliasTarget];
    } else {
      // 4. Kısmi / büyük-küçük harf duyarsız eşleşme
      const clubLower = clubName.toLowerCase().trim();
      const dbKey = Object.keys(CLUB_DATABASE).find(k => {
        const kLower = k.toLowerCase();
        return kLower === clubLower ||
               (kLower.length > 4 && clubLower.includes(kLower)) ||
               (clubLower.length > 4 && kLower.includes(clubLower));
      });

      if (dbKey && CLUB_DATABASE[dbKey]) {
        result = CLUB_DATABASE[dbKey];
      } else {
        // Alias'lar arasında da kısmi kontrol yap
        const aliasKey = Object.keys(CLUB_ALIASES).find(a => {
          const aLower = a.toLowerCase();
          return aLower === clubLower ||
                 (aLower.length > 4 && clubLower.includes(aLower)) ||
                 (clubLower.length > 4 && aLower.includes(clubLower));
        });

        if (aliasKey && CLUB_DATABASE[CLUB_ALIASES[aliasKey]]) {
          result = CLUB_DATABASE[CLUB_ALIASES[aliasKey]];
        } else {
          // 5. Bilinmeyen kulüp için dinamik kısaltma ve renk paleti
          const words = clubName.split(/[\s-]+/).filter(Boolean);
          let short = "";
          if (words.length === 1) {
            short = words[0].slice(0, 3).toUpperCase();
          } else if (words.length === 2) {
            short = (words[0].slice(0, 2) + words[1].slice(0, 1)).toUpperCase();
          } else {
            short = (words[0][0] + words[1][0] + words[2][0]).toUpperCase();
          }

          let hash = 0;
          for (let i = 0; i < clubName.length; i++) {
            hash = clubName.charCodeAt(i) + ((hash << 5) - hash);
          }

          const PALETTES = [
            { p: "#1E3A8A", s: "#3B82F6", t: "#FFFFFF" }, // Mavi
            { p: "#991B1B", s: "#EF4444", t: "#FFFFFF" }, // Kırmızı
            { p: "#065F46", s: "#10B981", t: "#FFFFFF" }, // Zümrüt
            { p: "#854D0E", s: "#FACC15", t: "#000000" }, // Altın
            { p: "#581C87", s: "#A855F7", t: "#FFFFFF" }, // Mor
            { p: "#18181B", s: "#71717A", t: "#FFFFFF" }, // Antrasit
            { p: "#0F766E", s: "#14B8A6", t: "#FFFFFF" }, // Teal
            { p: "#9A3412", s: "#FB923C", t: "#FFFFFF" }, // Turuncu
          ];

          const palette = PALETTES[Math.abs(hash) % PALETTES.length];

          result = {
            name: clubName,
            short: short.slice(0, 4),
            primaryColor: palette.p,
            secondaryColor: palette.s,
            textColor: palette.t,
            badgeShape: "shield",
          };
        }
      }
    }
  }

  BADGE_CACHE.set(clubName, result);
  return result;
}
